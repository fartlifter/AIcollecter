def summarize_with_gemini(raw_report_text: str, api_key: str = None) -> str:
    key = api_key or os.environ.get("GEMINI_API_KEY")
    if not key:
        return "❌ GEMINI_API_KEY가 설정되지 않았습니다."
    
    client = genai.Client(api_key=key)
    
    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=f"다음 수집된 기사들을 위의 [규칙]과 [작성 예시 템플릿]에 완벽하게 일치하도록 요약 정리해 출력하십시오. 특히 따옴표 정자 교정과 만 단위 미만 아라비아 숫자 표기(1억2000만원, 3000만원), 재판부 표기(합의/부장판사 삭제)를 엄격히 지키십시오:\n\n{raw_report_text}",
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_INSTRUCTION,
            temperature=0.1,
            thinking_config=types.ThinkingConfig(thinking_budget=1024)
        )
    )
    return response.text.strip()
